#!/usr/bin/env python3
"""Create a small, original, royalty-free synthetic scene for i2v evaluation."""
from pathlib import Path
from PIL import Image, ImageDraw


def create(path: Path) -> None:
    w, h = 512, 768
    im = Image.new("RGB", (w, h))
    draw = ImageDraw.Draw(im)
    # Sunset sky gradient
    for y in range(h):
        t = y / h
        draw.line([(0, y), (w, y)], fill=(
            int(18 + 104 * t), int(47 + 76 * t), int(103 - 36 * t)
        ))
    # Distant sun and scenery
    draw.ellipse((307, 105, 412, 210), fill=(255, 209, 146))
    draw.polygon([(0, 550), (110, 485), (240, 555), (400, 470), (512, 520), (512, 768), (0, 768)], fill=(24, 67, 85))
    draw.rectangle((0, 660, w, h), fill=(27, 58, 70))
    # Stylized water rocket
    draw.polygon([(256, 275), (215, 380), (297, 380)], fill=(224, 75, 77))
    draw.rounded_rectangle((219, 361, 293, 566), radius=15, fill=(239, 242, 239), outline=(41, 63, 91), width=4)
    draw.rectangle((232, 410, 280, 424), fill=(71, 167, 194))
    draw.ellipse((239, 445, 273, 479), fill=(69, 135, 185), outline=(31, 72, 108), width=3)
    draw.polygon([(220, 497), (188, 575), (221, 553)], fill=(220, 77, 77))
    draw.polygon([(292, 497), (324, 575), (291, 553)], fill=(220, 77, 77))
    # Flame plumes, drawn solely as input art; output is generated by the AI model.
    draw.polygon([(241, 566), (271, 566), (256, 634)], fill=(255, 179, 73))
    draw.polygon([(249, 566), (263, 566), (256, 611)], fill=(255, 229, 147))
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, format="PNG")
    print(f"Created synthetic test image: {path} ({w}x{h})")


if __name__ == "__main__":
    create(Path(__file__).resolve().parent / "output" / "source_rocket.png")
